#!/usr/bin/env node
// Regenerates the data-model tables in docs/TEMPLATE-SPEC.md from the code.
//
//   node cli/gen-spec.mjs           rewrite the tables
//   node cli/gen-spec.mjs --check   fail if they are stale (for CI)
//
// The prose in the spec is written by hand. The tables are not: they are the
// same SHAPES and LAYOUT_ROOTS the renderer projects and the validator checks
// against, so the document cannot drift from what a template actually gets.
// A spec that disagrees with the engine is worse than no spec, because an LLM
// will believe it.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

import { SHAPES, COMMON_ROOTS, LAYOUT_ROOTS } from "../shared/template/viewmodel.mjs";
import { REQUIRED_LAYOUTS, OPTIONAL_LAYOUTS, PARTIAL_CONTEXTS, ENGINE } from "../shared/template/manifest.mjs";
import { TOKEN_TYPES } from "../shared/template/tokens.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SPEC = path.join(ROOT, "docs", "TEMPLATE-SPEC.md");
const BEGIN = "<!-- BEGIN GENERATED -->";
const END = "<!-- END GENERATED -->";

// A pipe inside a type ("source|null") would otherwise end the table cell.
const cell = (v) => String(v).replace(/\|/g, "\\|");
const rows = (obj) => Object.entries(obj)
  .map(([k, v]) => `| \`${cell(k)}\` | \`${cell(v)}\` |`).join("\n");

const generated = `${BEGIN}
<!-- Generated by cli/gen-spec.mjs from shared/template/viewmodel.mjs. Do not edit by hand. -->

Engine: \`${ENGINE}\`

### Available in every layout

| Path | Type |
|---|---|
${rows(COMMON_ROOTS)}

### Extra roots, per layout

${Object.entries(LAYOUT_ROOTS).map(([layout, roots]) => {
  const required = REQUIRED_LAYOUTS.includes(layout) ? "required" : "optional";
  const body = Object.keys(roots).length
    ? `\n| Path | Type |\n|---|---|\n${rows(roots)}`
    : "\nNothing beyond the common roots.";
  return `**\`${layout}\`** (${required})${body}`;
}).join("\n\n")}

Required layouts: ${REQUIRED_LAYOUTS.map((l) => `\`${l}\``).join(", ")}.
Optional layouts: ${OPTIONAL_LAYOUTS.map((l) => `\`${l}\``).join(", ")}.

### Shapes

${Object.entries(SHAPES).map(([name, fields]) =>
  `**\`${name}\`**\n\n| Field | Type |\n|---|---|\n${rows(fields)}`).join("\n\n")}

\`theme\` is not in this table: its keys are whatever your own \`template.json\`
declares under \`"tokens"\`. A token named \`color.ink\` is read as
\`{{theme.color.ink}}\` and emitted as the CSS variable \`--color-ink\`.

### Token types

${TOKEN_TYPES.map((t) => `\`${t}\``).join(", ")}

### Partial contexts

A partial may declare the shape it is rendered against:
${PARTIAL_CONTEXTS.map((c) => `\`${c}\``).join(", ")}. Omit it and the partial may
only read the common roots above.

${END}`;

const current = await readFile(SPEC, "utf8");
const before = current.slice(0, current.indexOf(BEGIN));
const after = current.slice(current.indexOf(END) + END.length);

if (!current.includes(BEGIN) || !current.includes(END)) {
  console.error(`FATAL: ${SPEC} has no ${BEGIN} / ${END} markers.`);
  process.exit(1);
}

const next = before + generated + after;

if (process.argv.includes("--check")) {
  if (next !== current) {
    console.error("docs/TEMPLATE-SPEC.md is stale. Run: node cli/gen-spec.mjs");
    process.exit(1);
  }
  console.log("docs/TEMPLATE-SPEC.md is current.");
  process.exit(0);
}

await writeFile(SPEC, next);
console.log(`wrote the generated tables into ${path.relative(ROOT, SPEC)}`);
